export type LangCode = 'en' | 'id' | 'ja' | 'ko' | 'hi' | 'pt' | 'de' | 'fr' | 'es' | 'ms';

export const SUPPORTED_LANGUAGES: { code: LangCode; label: string }[] = [
  { code: 'id', label: 'Indonesia (ID)' },
  { code: 'en', label: 'English (EN)' },
  { code: 'ja', label: 'Japanese (JA)' },
  { code: 'ko', label: 'Korean (KO)' },
  { code: 'hi', label: 'Hindi (HI)' },
  { code: 'pt', label: 'Portuguese (PT)' },
  { code: 'de', label: 'German (DE)' },
  { code: 'fr', label: 'French (FR)' },
  { code: 'es', label: 'Spanish (ES)' },
  { code: 'ms', label: 'Malay (MS)' }
];

export function normalizeLang(raw?: string): LangCode {
  const s = (raw || '').toLowerCase().trim().split(/[-_]/)[0] as LangCode;
  return SUPPORTED_LANGUAGES.some((l) => l.code === s) ? s : 'en';
}

