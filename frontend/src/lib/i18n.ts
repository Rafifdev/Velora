export function tr(lang: LangCode | string, key: string, fallback?: string): string {
  const code = normalizeLang(lang);
  if (code === 'id') return ID[key] ?? EN[key] ?? fallback ?? key;
  if (code === 'en') return EN[key] ?? fallback ?? key;
  return PARTIALS[code]?.[key] ?? EN[key] ?? fallback ?? key;
}

export function getPrefLang(prefs: Record<string, string> | undefined): LangCode {
  return normalizeLang(prefs?.['content.language'] || (typeof navigator !== 'undefined' ? navigator.language : 'en'));
}
